"""Generate Lecdm/BuffData.lua: the spell IDs for every buff name in Lecdm/BuffList.lua.

Run it with no arguments: python3 tools/gen_data.py

It downloads WoW: Forever's SpellName table from wago.tools (product wowf) into .scratch/ (reused
for a day), then lists every spell ID whose name matches one of the names in BuffList.lua.
Matching by name picks up all ranks and the group versions. Names with no IDs are reported, so a
typo or a spell Forever doesn't have shows up here rather than as an icon that never lights.
"""
import csv
import datetime
import pathlib
import re
import sys
import time
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
LIST = ROOT / "Lecdm" / "BuffList.lua"
DATA = ROOT / "Lecdm" / "BuffData.lua"
CACHE = ROOT / ".scratch" / "SpellName.csv"
URL = "https://wago.tools/db2/SpellName/csv?product=wowf"


def spell_names():
    if not CACHE.exists() or time.time() - CACHE.stat().st_mtime > 86400:
        CACHE.parent.mkdir(exist_ok=True)
        print(f"Downloading {URL}")
        request = urllib.request.Request(URL, headers={"User-Agent": "Lecdm gen_data (github.com/addohm/lecdm)"})
        with urllib.request.urlopen(request, timeout=120) as response:
            CACHE.write_bytes(response.read())
    with CACHE.open(encoding="utf-8", newline="") as f:
        return [(int(row["ID"]), row["Name_lang"]) for row in csv.DictReader(f)]


def wanted_names():
    """The entries' names: string literals right after "{" or "," (not field values like
    class = "WARRIOR", not section names or code), comments left out."""
    source = "\n".join(line for line in LIST.read_text(encoding="utf-8").splitlines()
                       if not line.lstrip().startswith("--"))
    names = []
    for m in re.finditer(r'"((?:[^"\\]|\\.)*)"', source):
        before = source[:m.start()].rstrip()
        if before.endswith("{") or before.endswith(","):
            name = m.group(1).replace('\\"', '"').replace("\\\\", "\\")
            if name not in names:
                names.append(name)
    return names


def lua_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    names = wanted_names()
    ids = {name: [] for name in names}
    for spell_id, name in spell_names():
        if name in ids:
            ids[name].append(spell_id)

    missing = [name for name in names if not ids[name]]
    lines = [
        "-- GENERATED by tools/gen_data.py from wago.tools SpellName (product wowf), "
        + datetime.date.today().isoformat() + ". Don't edit by hand.",
        "-- Every spell ID with each buff name in BuffList.lua.",
        "local _, ns = ...",
        "",
        "ns.BuffIDs = {",
    ]
    for name in names:
        if ids[name]:
            lines.append(f"\t[{lua_string(name)}] = {{ {', '.join(str(i) for i in sorted(ids[name]))} }},")
    lines.append("}")
    DATA.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")

    print(f"Wrote {DATA.relative_to(ROOT)}: {len(names)} names, {sum(len(v) for v in ids.values())} IDs")
    if missing:
        print("No spell IDs for: " + ", ".join(missing))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
